// Maintainer-only: bundle the pinned standard parser with Workers' IDNA adapter.
// The checked-in output keeps consumers independent of Node.js and build hooks.
import { build } from "esbuild";
import { format } from "prettier";
import { readFile, writeFile } from "node:fs/promises";
const packageInfo = JSON.parse(
  await readFile(
    new URL("../../node_modules/whatwg-url/package.json", import.meta.url),
  ),
);
if (packageInfo.version !== "17.3.0")
  throw Error("Unexpected whatwg-url version");
const result = await build({
  stdin: {
    contents: `import * as wrappers from "whatwg-url/webidl2js-wrapper.js";
const scope={Array,Object,Promise,String,TypeError};
wrappers.URL.install(scope,["Window"]);
wrappers.URLSearchParams.install(scope,["Window"]);
export const URL=scope.URL;`,
    resolveDir: process.cwd(),
  },
  bundle: true,
  format: "esm",
  platform: "browser",
  write: false,
  legalComments: "inline",
  plugins: [
    {
      name: "workers-idna",
      setup(b) {
        b.onLoad({ filter: /whatwg-url\/lib\/utils\.js$/ }, async (args) => {
          let contents = await readFile(args.path, "utf8");
          const original =
            'const sharedArrayBufferByteLengthGetter =\n  Object.getOwnPropertyDescriptor(SharedArrayBuffer.prototype, "byteLength").get;';
          if (!contents.includes(original))
            throw new Error("Upstream WebIDL buffer guard changed");
          contents = contents.replace(
            original,
            'const sharedArrayBufferByteLengthGetter = typeof SharedArrayBuffer === "function" ? Object.getOwnPropertyDescriptor(SharedArrayBuffer.prototype, "byteLength").get : () => { throw new TypeError("SharedArrayBuffer is unavailable"); };',
          );
          // URL exposes no async iterators. Avoid probing generator intrinsics
          // in the unused WebIDL fallback: the runtime build lowers generators.
          const asyncPrototype =
            "const AsyncIteratorPrototype = Object.getPrototypeOf(Object.getPrototypeOf(async function* () {}).prototype);";
          if (!contents.includes(asyncPrototype))
            throw new Error("Upstream WebIDL async iterator fallback changed");
          contents = contents.replace(
            asyncPrototype,
            "const AsyncIteratorPrototype = { [Symbol.asyncIterator]() { return this; } };",
          );
          return { contents, loader: "js" };
        });

        b.onResolve(
          {
            filter:
              /^(?:webidl-conversions|@exodus\/bytes\/(?:encoding|whatwg)\.js)$/,
          },
          (a) => ({ path: a.path, namespace: "platform" }),
        );
        b.onLoad({ filter: /.*/, namespace: "platform" }, (a) => ({
          contents: a.path.endsWith("encoding.js")
            ? "export {};"
            : a.path === "webidl-conversions"
              ? 'export {USVString, any} from \"./parser-platform.js\";'
              : 'export {percentEncodeAfterEncoding} from \"./parser-platform.js\";',
          loader: "js",
        }));
        b.onResolve(
          { filter: /^\.\/parser-platform\.js$/, namespace: "platform" },
          () => ({ path: "./parser-platform.js", external: true }),
        );
        b.onResolve({ filter: /^tr46$/ }, () => ({
          path: "workers-idna",
          namespace: "workers-idna",
        }));
        b.onLoad({ filter: /.*/, namespace: "workers-idna" }, () => ({
          contents: 'import {toASCII} from "./unicode.js"; export {toASCII};',
          loader: "js",
        }));
        b.onResolve(
          { filter: /^\.\/unicode\.js$/, namespace: "workers-idna" },
          () => ({ path: "./unicode.js", external: true }),
        );
      },
    },
  ],
});
const output =
  "// @ts-nocheck\n// Generated by scripts/url-idna/bundle-url.mjs. See LICENSE-3RD-PARTY.md.\n" +
  (await format(result.outputFiles[0].text, { parser: "typescript" }));
const target = new URL("../../src/compat/url/standard-url.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "URL parser is stale; run node scripts/url-idna/bundle-url.mjs",
    );
} else {
  await writeFile(target, output);
}
