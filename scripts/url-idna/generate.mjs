// Maintainer-only: regenerate the IDNA tables from workerd's pinned Ada source.
// Requires a C++20 compiler; neither consumers nor builds require this tool.
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
const version = "4.0.0";
const checksum =
  "c153db7a5a9f8a92a313dff0fecbbb28198542fc98bf024b961baf9896408347";
const dir = await mkdtemp(join(tmpdir(), "workers-url-idna-"));
try {
  const response = await fetch(
    `https://crates.io/api/v1/crates/ada-url/${version}/download`,
  );
  if (!response.ok) throw new Error(`Download failed: ${response.status}`);
  const archive = Buffer.from(await response.arrayBuffer());
  if (createHash("sha256").update(archive).digest("hex") !== checksum)
    throw new Error("Ada archive checksum mismatch");
  await writeFile(join(dir, "ada.tar.gz"), archive);
  execFileSync("tar", ["-xzf", join(dir, "ada.tar.gz"), "-C", dir]);
  const deps = join(dir, `ada-url-${version}`, "deps");
  await writeFile(
    join(deps, "extract.cpp"),
    await readFile(new URL("./extract.cpp", import.meta.url)),
  );
  execFileSync(process.env.CXX || "c++", [
    "-std=c++20",
    "-O2",
    join(deps, "extract.cpp"),
    "-o",
    join(dir, "extract"),
  ]);
  const tables = JSON.parse(
    execFileSync(join(dir, "extract"), { maxBuffer: 1024 * 1024 }),
  );
  const source = await readFile(join(deps, "ada.cpp"), "utf8");
  for (const name of ["virama", "R", "L", "D"]) {
    const body = source.match(
      new RegExp(
        `constexpr static uint32_t ${name}\\[\\] = \\{([\\s\\S]*?)\\};`,
      ),
    )[1];
    tables[name] = body.match(/0x[0-9a-f]+/gi).map(Number);
  }
  const bytes = Buffer.from(tables.strings),
    strings = {};
  for (const [, , status] of tables.mapping)
    if (status !== tables.valid && status !== tables.disallowed)
      strings[status] = bytes
        .subarray(status, bytes.indexOf(0, status))
        .toString("utf8");
  tables.strings = strings;
  const header =
    "// Generated by scripts/url-idna/generate.mjs from Ada 4.0.0 (workerd 1.20261012.1).\n// See LICENSE-ADA and LICENSE-3RD-PARTY.md. Do not edit tables manually.\n";
  let output = header;
  for (const [name, value] of Object.entries(tables))
    output += `// prettier-ignore\nexport const ${name} = ${JSON.stringify(value)};\n`;
  await writeFile(
    new URL("../../src/compat/url/idna-data.ts", import.meta.url),
    output,
  );
} finally {
  await rm(dir, { recursive: true, force: true });
}
